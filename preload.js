const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  scanMedia: () => ipcRenderer.invoke('media:scan'),
  openFolder: (kind) => ipcRenderer.invoke('media:openFolder', kind),
  authLogin: () => ipcRenderer.invoke('auth:login'),
  authMe: () => ipcRenderer.invoke('auth:me'),
  spotifyConnect: (clientId) => ipcRenderer.invoke('spotify:connect', clientId),
  spotifyDisconnect: () => ipcRenderer.invoke('spotify:disconnect'),
  spotifyApi: (req) => ipcRenderer.invoke('spotify:api', req),
  mediaCmd: (cmd) => ipcRenderer.invoke('media:cmd', cmd),
  artLookup: (artist, title) => ipcRenderer.invoke('art:lookup', artist, title),
  authSetCookie: (cookie) => ipcRenderer.invoke('auth:setCookie', cookie),
  authLogout: () => ipcRenderer.invoke('auth:logout'),
  openRobloxWindow: (url) => ipcRenderer.invoke('auth:openWindow', url),
  addBackgrounds: () => ipcRenderer.invoke('bg:add'),
  deleteBackground: (name) => ipcRenderer.invoke('bg:delete', name),
  fetchJson: (url, opts) => ipcRenderer.invoke('net:json', url, opts),
  launch: (placeId) => ipcRenderer.invoke('game:launch', placeId),
  chooseFont: () => ipcRenderer.invoke('font:choose'),
  removeFont: () => ipcRenderer.invoke('font:remove'),
  uiFontUrl: () => ipcRenderer.invoke('uifont:url'),
  chooseUiFont: () => ipcRenderer.invoke('uifont:choose'),
  removeUiFont: () => ipcRenderer.invoke('uifont:remove'),
  effectsConfig: () => ipcRenderer.invoke('config:effects'),
  tagsConfig: () => ipcRenderer.invoke('config:tags'),
  banCheck: (id) => ipcRenderer.invoke('ban:check', id),
  grantsGet: () => ipcRenderer.invoke('config:grants'),
  lookGet: (ids) => ipcRenderer.invoke('look:get', ids),
  groupSave: () => ipcRenderer.invoke('group:save'),
  accountsList: () => ipcRenderer.invoke('accounts:list'),
  accountsSwitch: (id) => ipcRenderer.invoke('accounts:switch', id),
  accountsRemove: (id) => ipcRenderer.invoke('accounts:remove', id),
  accountsPrepareAdd: () => ipcRenderer.invoke('accounts:prepareAdd'),
  joinFriend: (placeId, gameId) => ipcRenderer.invoke('game:join', placeId, gameId),
  launchError: () => ipcRenderer.invoke('game:lastError'),
  openLink: (url) => ipcRenderer.invoke('link:open', url),
  win: {
    min: () => ipcRenderer.send('win:min'),
    max: () => ipcRenderer.send('win:max'),
    close: () => ipcRenderer.send('win:close'),
  },
});
